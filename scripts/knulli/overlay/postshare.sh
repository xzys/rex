#!/bin/bash
# postshare.sh — preseeded onto the BATOCERA (FAT32) partition of a
# rex-edition KNULLI image. Runs at S12populateshare on every boot.
# Idempotent.
#
# On first boot, knulli's autoresize (S02resize) grows the SHARE partition to
# fill the card and formats it exFAT. We convert exFAT → ext4 in place
# (umount -l + mkfs.ext4 + remount) so the Debian chroot gets Unix perms.
# Then we copy bundles, extract the payload, wire custom.sh, and let ES hand
# off to rex-firstboot.sh → Rex.
#
# Single boot — no extra reboot needed.

set -u

ACTION="${1:-start}"
[ "$ACTION" = "start" ] || exit 0

# Guard: if we're being called from our own S12 repopulate re-invocation
# after the reformat, exit silently so we don't double-extract.
if [ "${REX_POSTSHARE_REPOPULATE_ONLY:-0}" = "1" ]; then
    echo "postshare: nested call during userdata repopulate, skipping rex setup"
    exit 0
fi

MARKER_DONE=/userdata/.rex-bootstrap-done
BOOT_BUNDLE=/boot/rex-bundle
BUNDLE=/userdata/rex-bundle
PAYLOAD="$BUNDLE/rex-payload.tar.gz"
STAGE=/userdata/rex-install
SHARE_DEV=/dev/mmcblk0p5

[ -f "$MARKER_DONE" ] && exit 0

# --- Convert SHARE to ext4 if needed -----------------------------------
SHARE_FS="$(blkid -o value -s TYPE "$SHARE_DEV" 2>/dev/null || true)"

if [ "$SHARE_FS" != "ext4" ]; then
    echo "postshare: SHARE is ${SHARE_FS:-unknown}, converting to ext4" >&2

    # Try regular unmount first, fall back to lazy. Force (-F) mkfs.ext4
    # handles any remaining busy state on the block device.
    umount /userdata 2>/dev/null || umount -l /userdata 2>/dev/null || true

    mkfs.ext4 -F -F -L SHARE "$SHARE_DEV" || {
        echo "postshare: mkfs.ext4 failed" >&2
        mount "$SHARE_DEV" /userdata 2>/dev/null || true
        exit 1
    }

    mount "$SHARE_DEV" /userdata || {
        echo "postshare: mount after ext4 conversion failed" >&2
        exit 1
    }

    # S12populateshare populated the old /userdata before this script ran;
    # mkfs wiped that skeleton. Re-run S12 to recreate batocera.conf,
    # machine-id, ssh dirs, rom dirs, etc. on the fresh ext4.
    if [ -x /etc/init.d/S12populateshare ]; then
        echo "postshare: repopulating default userdata on ext4"
        REX_POSTSHARE_REPOPULATE_ONLY=1 /etc/init.d/S12populateshare start || true
    fi
fi

# --- Copy bundles from BATOCERA to SHARE --------------------------------
if [ -d "$BOOT_BUNDLE" ]; then
    mkdir -p "$BUNDLE"
    if [ -f "$BOOT_BUNDLE/rex-payload.tar.gz" ] && [ ! -f "$BUNDLE/rex-payload.tar.gz" ]; then
        cp "$BOOT_BUNDLE/rex-payload.tar.gz" "$BUNDLE/rex-payload.tar.gz"
    fi
fi

[ -f "$PAYLOAD" ] || { echo "postshare: payload not found" >&2; exit 1; }

# --- Extract payload ----------------------------------------------------
rm -rf "$STAGE"
mkdir -p "$STAGE"
tar xzf "$PAYLOAD" -C "$STAGE" --no-same-owner

INNER="$(find "$STAGE" -maxdepth 1 -mindepth 1 -type d | head -n1)"
[ -d "$INNER" ] || { echo "postshare: no payload dir found" >&2; exit 1; }

# --- Wire custom.sh → rex-firstboot.sh ----------------------------------
mkdir -p /userdata/system
cat > /userdata/system/custom.sh <<CUSTOM_EOF
#!/bin/bash
# Auto-generated by rex postshare.sh. Owns rex install + autostart.
exec /boot/rex-firstboot.sh "$INNER" >> /var/log/rex-firstboot.log 2>&1
CUSTOM_EOF
chmod +x /userdata/system/custom.sh

touch "$MARKER_DONE"
echo "postshare: install ready, handing off to rex-firstboot.sh" >&2
exit 0
