#!/bin/bash
# postshare.sh — preseeded onto the BATOCERA (FAT32) partition of a
# rex-edition KNULLI image. Runs at S12populateshare on every boot.
# Idempotent.
#
# Two-boot strategy (no format-internal, no gdisk):
#
#   Boot 1: Knulli's autoresize grows SHARE to full card as exFAT, disarms.
#           We detect a non-ext4 /userdata, drop /boot/boot-custom.sh (an S00
#           hook that runs mkfs.ext4 on the unmounted device), and reboot.
#
#   Boot 2: S00bootcustom runs boot-custom.sh before anything mounts SHARE.
#           Device is full-size (autoresize did that) and unmounted, so
#           mkfs.ext4 succeeds cleanly — no e2fsprogs-1.47 "in use" rejection,
#           no gdisk GPT corruption. boot-custom.sh deletes itself on success.
#           S11share mounts ext4, S12 populates the skeleton, then we install.
#
# Why not single-boot: an in-place reformat (umount -l + mkfs.ext4) fails on
# Knulli because exFAT is FUSE-mounted at /userdata AND /media/SHARE, and
# e2fsprogs 1.47 refuses to mkfs a device with lingering FUSE handles even
# after lazy-unmounting both.

set -u

ACTION="${1:-start}"
[ "$ACTION" = "start" ] || exit 0

MARKER_DONE=/userdata/.rex-bootstrap-done
BOOT_BUNDLE=/boot/rex-bundle
BUNDLE=/userdata/rex-bundle
PAYLOAD="$BUNDLE/rex-payload.tar.gz"
STAGE=/userdata/rex-install
BOOTCUSTOM=/boot/boot-custom.sh

[ -f "$MARKER_DONE" ] && exit 0

# The *mounted* filesystem type of /userdata. Kernel ext4 shows "ext4";
# FUSE-mounted exFAT shows "fuseblk"; S11share's fallback shows "tmpfs".
# blkid on the device and `stat -f %T` are both wrong here: blkid reports
# the on-disk fs even when the mount fell back to tmpfs, and stat prints
# "ext2/ext3" for ext4 mounts (shared f_type magic).
SHARE_FS="$(awk '$2 == "/userdata" {print $3}' /proc/mounts | tail -n1)"

# --- Boot 1: not ext4 — stage the S00 conversion and reboot -------------
if [ "$SHARE_FS" != "ext4" ]; then
    echo "postshare: /userdata is ${SHARE_FS:-unmounted}, staging S00 ext4 conversion" >&2

    # Guard against reboot loops — if boot-custom.sh survives a previous
    # attempt, the conversion failed; leave ES up for debugging.
    if [ -f "$BOOTCUSTOM" ]; then
        echo "postshare: $BOOTCUSTOM already exists, not rebooting" >&2
        exit 0
    fi

    mount -o remount,rw /boot 2>/dev/null || true
    cat > "$BOOTCUSTOM" <<'BOOTCUSTOM_EOF'
#!/bin/sh
# Auto-generated by rex postshare.sh — converts SHARE to ext4 at S00,
# before anything mounts it, then deletes itself.
[ "$1" = "start" ] || exit 0
DEV=/dev/mmcblk0p5
FS="$(blkid -o value -s TYPE "$DEV" 2>/dev/null || true)"
if [ "$FS" != "ext4" ]; then
    mkfs.ext4 -q -F -L SHARE "$DEV" || exit 1
fi
# Success (or already converted): remove self so postshare's loop guard
# stays meaningful and this hook can never fire again.
mount -o remount,rw /boot 2>/dev/null || true
rm -f /boot/boot-custom.sh
sync
BOOTCUSTOM_EOF

    if [ ! -s "$BOOTCUSTOM" ]; then
        echo "postshare: failed to write $BOOTCUSTOM, leaving ES up" >&2
        exit 1
    fi
    sync

    echo "postshare: rebooting for ext4 conversion" >&2
    reboot
    exit 0
fi

# --- Boot 2: ext4 — install rex ----------------------------------------
# S12populateshare populated the skeleton on this fresh ext4 before invoking
# us, so no repopulation dance is needed — straight to the install.
echo "postshare: /userdata is ext4, proceeding with rex install" >&2

# --- Copy bundles from BATOCERA to SHARE --------------------------------
if [ -d "$BOOT_BUNDLE" ]; then
    mkdir -p "$BUNDLE"
    if [ -f "$BOOT_BUNDLE/rex-payload.tar.gz" ] && [ ! -f "$BUNDLE/rex-payload.tar.gz" ]; then
        cp "$BOOT_BUNDLE/rex-payload.tar.gz" "$BUNDLE/rex-payload.tar.gz"
    fi
fi

[ -f "$PAYLOAD" ] || { echo "postshare: payload not found" >&2; exit 1; }

# --- Extract payload ----------------------------------------------------
rm -rf "$STAGE"
mkdir -p "$STAGE"
tar xzf "$PAYLOAD" -C "$STAGE" --no-same-owner

INNER="$(find "$STAGE" -maxdepth 1 -mindepth 1 -type d | head -n1)"
[ -d "$INNER" ] || { echo "postshare: no payload dir found" >&2; exit 1; }

# --- Wire custom.sh → rex-firstboot.sh ----------------------------------
mkdir -p /userdata/system
cat > /userdata/system/custom.sh <<CUSTOM_EOF
#!/bin/bash
# Auto-generated by rex postshare.sh. Owns rex install + autostart.
exec /boot/rex-firstboot.sh "$INNER" >> /var/log/rex-firstboot.log 2>&1
CUSTOM_EOF
chmod +x /userdata/system/custom.sh

# Leftover from the conversion boot, in case the S00 hook couldn't remove it.
rm -f "$BOOTCUSTOM" 2>/dev/null || true

touch "$MARKER_DONE"
echo "postshare: install ready, handing off to rex-firstboot.sh" >&2
exit 0
