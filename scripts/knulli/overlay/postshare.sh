#!/bin/bash
# postshare.sh — preseeded onto the BATOCERA (FAT32) partition of a rex-edition
# KNULLI image. Runs after /userdata mounts but before EmulationStation starts.
# Idempotent: bails out on every boot after the first.
#
# Job: stage rex-payload.tar.gz from /boot into /userdata, then drop a
# /userdata/system/custom.sh that wires the rest of the install + autostart.
# The heavy lifting (apt, chroot download) needs network and happens out of
# postshare.sh because postshare blocks boot.

set -eu

MARKER=/userdata/.rex-bootstrap-done
PAYLOAD=/boot/rex-payload.tar.gz
STAGE=/userdata/rex-install

[ -f "$MARKER" ] && exit 0
[ -f "$PAYLOAD" ] || exit 0

mkdir -p "$STAGE"
tar xzf "$PAYLOAD" -C "$STAGE"

# Find the extracted top-level dir (rex-brick-<version>) — package.sh nests one level.
INNER="$(find "$STAGE" -maxdepth 1 -mindepth 1 -type d | head -n1)"
[ -d "$INNER" ] || exit 0

# Write custom.sh — runs after ES launches on every subsequent boot.
mkdir -p /userdata/system
cat > /userdata/system/custom.sh <<EOF
#!/bin/bash
# Auto-generated by rex postshare.sh on first boot. Owns rex install + autostart.
exec /boot/rex-firstboot.sh "$INNER" >> /var/log/rex-firstboot.log 2>&1
EOF
chmod +x /userdata/system/custom.sh

touch "$MARKER"
exit 0
